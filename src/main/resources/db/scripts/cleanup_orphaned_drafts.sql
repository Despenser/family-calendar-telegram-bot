-- ============================================================================
-- Скрипт очистки осиротевших черновиков событий
-- ============================================================================
-- Описание: Удаляет черновики событий с NULL значениями в обязательных полях
-- Назначение: Одноразовая очистка существующих осиротевших черновиков
-- Требования: 1.4
-- ============================================================================

-- Критерии осиротевшего черновика:
-- 1. Статус = 'DRAFT'
-- 2. title = NULL
-- 3. event_date = NULL
-- 4. event_time = NULL
-- 5. created_at старше 1 часа (для безопасности)

-- ----------------------------------------------------------------------------
-- Шаг 1: Просмотр осиротевших черновиков перед удалением
-- ----------------------------------------------------------------------------
-- Выполните этот запрос, чтобы увидеть, какие черновики будут удалены
SELECT 
    id,
    user_id,
    family_id,
    title,
    event_date,
    event_time,
    status,
    created_at,
    EXTRACT(EPOCH FROM (CURRENT_TIMESTAMP - created_at))/3600 AS age_hours
FROM events
WHERE status = 'DRAFT'
  AND title IS NULL
  AND event_date IS NULL
  AND event_time IS NULL
  AND created_at < CURRENT_TIMESTAMP - INTERVAL '1 hour'
ORDER BY created_at;

-- ----------------------------------------------------------------------------
-- Шаг 2: Удаление осиротевших черновиков
-- ----------------------------------------------------------------------------
-- ВНИМАНИЕ: Эта операция необратима! Убедитесь, что вы проверили результаты
-- запроса из Шага 1 перед выполнением удаления.

-- Удаление черновиков старше 1 часа
DELETE FROM events
WHERE status = 'DRAFT'
  AND title IS NULL
  AND event_date IS NULL
  AND event_time IS NULL
  AND created_at < CURRENT_TIMESTAMP - INTERVAL '1 hour';

-- Получение количества удаленных записей
-- (В PostgreSQL можно использовать RETURNING для подсчета)
-- Альтернативно, выполните этот запрос после удаления:
-- SELECT COUNT(*) FROM events WHERE status = 'DRAFT';

-- ----------------------------------------------------------------------------
-- Шаг 3: Проверка результатов
-- ----------------------------------------------------------------------------
-- Проверьте, что осиротевших черновиков больше нет
SELECT COUNT(*) as remaining_orphaned_drafts
FROM events
WHERE status = 'DRAFT'
  AND title IS NULL
  AND event_date IS NULL
  AND event_time IS NULL;

-- Проверьте общее количество черновиков в системе
SELECT COUNT(*) as total_drafts
FROM events
WHERE status = 'DRAFT';

