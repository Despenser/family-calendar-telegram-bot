-- ----------------------------------------------------------------------------
-- Обновление существующих данных
-- ----------------------------------------------------------------------------
-- Эта миграция выполняется в отдельной транзакции после V20, поэтому
-- новые значения ENUM уже зафиксированы и могут быть использованы
-- ----------------------------------------------------------------------------

-- Обновляем все существующие записи на новые значения в UPPER_CASE
UPDATE reminders 
SET reminder_type = 'MORNING_OF_DAY'::reminder_type 
WHERE reminder_type = 'morning_of_day'::reminder_type;

UPDATE reminders 
SET reminder_type = 'EVENING_BEFORE'::reminder_type 
WHERE reminder_type = 'evening_before'::reminder_type;

UPDATE reminders 
SET reminder_type = 'ONE_HOUR_BEFORE'::reminder_type 
WHERE reminder_type = 'one_hour_before'::reminder_type;

UPDATE reminders 
SET reminder_type = 'TEN_MINUTES_BEFORE'::reminder_type 
WHERE reminder_type = 'ten_minutes_before'::reminder_type;

UPDATE reminders 
SET reminder_type = 'CUSTOM'::reminder_type 
WHERE reminder_type = 'custom'::reminder_type;

-- ============================================================================
-- Примечания:
-- 
-- 1. Эта миграция обновляет все существующие записи с старых значений
--    (snake_case) на новые значения (UPPER_CASE)
--
-- 2. После этой миграции все существующие напоминания будут использовать
--    новый формат значений
--
-- 3. Новые записи, создаваемые Hibernate, будут автоматически использовать
--    UPPER_CASE значения
--
-- 4. Старые значения ENUM остаются в типе для обратной совместимости,
--    но больше не используются в данных
-- ============================================================================
