-- ============================================================================
-- Миграция V19: Добавление поля timezone для пользователей
-- ============================================================================
-- Описание: Добавление колонки timezone в таблицу users для хранения
--           часового пояса пользователя в формате IANA (например, Europe/Moscow)
-- Требования: 5.1, 5.2, 5.3
-- ============================================================================

-- Добавляем колонку timezone в таблицу users
-- Используем IF NOT EXISTS для идемпотентности миграции
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 
        FROM information_schema.columns 
        WHERE table_name = 'users' 
        AND column_name = 'timezone'
    ) THEN
        ALTER TABLE users 
        ADD COLUMN timezone VARCHAR(50) DEFAULT 'Europe/Moscow';
        
        RAISE NOTICE 'Колонка timezone успешно добавлена в таблицу users';
    ELSE
        RAISE NOTICE 'Колонка timezone уже существует в таблице users, пропускаем';
    END IF;
END $$;

-- Комментарий для новой колонки
COMMENT ON COLUMN users.timezone IS 'Часовой пояс пользователя в формате IANA (например, Europe/Moscow). Используется для корректной валидации и отображения дат и времени событий';

-- ============================================================================
-- Конец миграции V19
-- ============================================================================
