-- ============================================================================
-- Миграция V15: Добавление флага шапки корзины к событиям
-- ============================================================================
-- Описание: Добавление колонки is_trash_header в таблицу events для
--           отслеживания первого события в корзине.
--           Это позволит сохранять шапку корзины при редактировании первого события.
-- Требования: 5.1, 5.2, 5.3, 5.4
-- ============================================================================

-- Добавляем колонку is_trash_header в таблицу events
ALTER TABLE events 
ADD COLUMN is_trash_header BOOLEAN NOT NULL DEFAULT FALSE;

-- Комментарий для новой колонки
COMMENT ON COLUMN events.is_trash_header IS 'Флаг, указывающий, что сообщение этого события содержит шапку корзины. Используется для корректного обновления первого события в корзине с сохранением шапки "🗑️ Корзина" и информации о количестве событий в корзине.';

-- Создаем индекс для быстрого поиска события с шапкой корзины
-- Индекс используется для эффективного поиска первого события в корзине пользователя
CREATE INDEX idx_events_trash_header 
ON events(user_id, is_trash_header) 
WHERE status = 'DELETED' AND is_trash_header = TRUE;

-- Устанавливаем флаг TRUE для первых событий в корзине каждого пользователя
-- Первое событие определяется как событие с самой ранней датой и временем
-- среди удаленных событий пользователя (статус = 'DELETED')
WITH first_trash_events AS (
    SELECT DISTINCT ON (user_id) id
    FROM events
    WHERE status = 'DELETED'
    ORDER BY user_id, deleted_at NULLS LAST, event_date NULLS LAST, event_time NULLS LAST, id
)
UPDATE events
SET is_trash_header = TRUE
WHERE id IN (SELECT id FROM first_trash_events);

