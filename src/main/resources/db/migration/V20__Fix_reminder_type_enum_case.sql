-- ============================================================================
-- Миграция V20: Исправление регистра значений ENUM reminder_type
-- ============================================================================
-- Описание: Добавление UPPER_CASE значений в ENUM reminder_type для
--           соответствия Java константам
-- Требования: 1.1, 1.2, 1.3, 2.1
-- Проблема: Hibernate с @Enumerated(EnumType.STRING) сохраняет значения
--           в UPPER_CASE, но PostgreSQL ENUM содержит значения в snake_case
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Добавление новых значений ENUM в UPPER_CASE формате
-- ----------------------------------------------------------------------------
-- ВАЖНО: PostgreSQL требует, чтобы новые значения ENUM были зафиксированы
-- перед использованием. Поэтому мы добавляем значения в этой миграции,
-- а обновление данных будет в следующей миграции V21.
-- ----------------------------------------------------------------------------

-- Добавляем новые значения, которые соответствуют Java константам
ALTER TYPE reminder_type ADD VALUE IF NOT EXISTS 'MORNING_OF_DAY';
ALTER TYPE reminder_type ADD VALUE IF NOT EXISTS 'EVENING_BEFORE';
ALTER TYPE reminder_type ADD VALUE IF NOT EXISTS 'ONE_HOUR_BEFORE';
ALTER TYPE reminder_type ADD VALUE IF NOT EXISTS 'TEN_MINUTES_BEFORE';
ALTER TYPE reminder_type ADD VALUE IF NOT EXISTS 'FIFTEEN_MINUTES_BEFORE';
ALTER TYPE reminder_type ADD VALUE IF NOT EXISTS 'CUSTOM';


-- ----------------------------------------------------------------------------
-- Комментарии
-- ----------------------------------------------------------------------------

COMMENT ON TYPE reminder_type IS 
    'Тип напоминания: MORNING_OF_DAY (утром в день события), EVENING_BEFORE (вечером накануне), ONE_HOUR_BEFORE (за 1 час), TEN_MINUTES_BEFORE (за 10 минут, deprecated), FIFTEEN_MINUTES_BEFORE (за 15 минут), CUSTOM (свое время). Старые значения в snake_case сохранены для обратной совместимости.';

-- ============================================================================
-- Примечания:
-- 
-- 1. Новые значения в UPPER_CASE добавлены для соответствия Java константам
--
-- 2. Старые значения (morning_of_day, evening_before и т.д.) остаются в ENUM
--    для обратной совместимости
--
-- 3. Обновление существующих данных будет выполнено в миграции V21
--
-- 4. PostgreSQL требует, чтобы новые значения ENUM были зафиксированы
--    (committed) перед использованием, поэтому мы разделили миграцию на две части
--
-- 5. Новое значение FIFTEEN_MINUTES_BEFORE добавлено для замены устаревшего
--    TEN_MINUTES_BEFORE
-- ============================================================================
-- Конец миграции V20
-- ============================================================================
