-- Миграция V14: Добавление флага шапки "Мои события" к событиям
-- ============================================================================
-- Описание: Добавление колонки is_my_events_header в таблицу events для
--           отслеживания первого события в списке "Мои события".
--           Это позволит сохранять шапку списка при редактировании первого события.
-- Требования: 2.1
-- ============================================================================

-- Добавляем колонку is_my_events_header в таблицу events
ALTER TABLE events 
ADD COLUMN is_my_events_header BOOLEAN NOT NULL DEFAULT FALSE;

-- Комментарий для новой колонки
COMMENT ON COLUMN events.is_my_events_header IS 'Флаг, указывающий, что сообщение этого события содержит шапку списка "Мои события". Используется для корректного обновления первого события в списке с сохранением шапки "📋 Мои события" и информации о количестве событий.';

-- Устанавливаем флаг TRUE для первых событий каждого пользователя
-- Первое событие определяется как событие с самой ранней датой и временем
-- среди активных событий пользователя (статус != 'DELETED')
WITH first_events AS (
    SELECT DISTINCT ON (user_id) id
    FROM events
    WHERE status != 'DELETED'
    ORDER BY user_id, event_date NULLS LAST, event_time NULLS LAST, id
)
UPDATE events
SET is_my_events_header = TRUE
WHERE id IN (SELECT id FROM first_events);

