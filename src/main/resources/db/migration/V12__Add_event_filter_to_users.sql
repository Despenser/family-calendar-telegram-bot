-- ============================================================================
-- Описание: Добавление колонки event_filter в таблицу users для хранения
--           предпочтений пользователя по фильтрации событий
-- Требования: 3.4
-- ============================================================================

-- Добавляем колонку event_filter в таблицу users
ALTER TABLE users 
ADD COLUMN event_filter VARCHAR(20) DEFAULT 'ALL';

-- Комментарий для новой колонки
COMMENT ON COLUMN users.event_filter IS 'Фильтр отображения событий: ALL (все события), FAMILY (семейные), PERSONAL (личные)';

