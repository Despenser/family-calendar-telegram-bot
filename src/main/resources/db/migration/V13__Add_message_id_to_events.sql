-- ============================================================================
-- Миграция V13: Добавление идентификатора сообщения Telegram к событиям
-- ============================================================================
-- Описание: Добавление колонки message_id в таблицу events для хранения
--           идентификатора сообщения Telegram, связанного с событием.
--           Это позволит обновлять существующие сообщения вместо создания новых.
-- Требования: 6.1, 6.2, 6.3, 6.4, 6.5
-- ============================================================================

-- Добавляем колонку message_id в таблицу events
ALTER TABLE events 
ADD COLUMN message_id BIGINT;

-- Комментарий для новой колонки
COMMENT ON COLUMN events.message_id IS 'Идентификатор сообщения Telegram, связанного с событием. Используется для обновления сообщения при редактировании события. NULL для событий, созданных до внедрения этой функции или для событий, сообщения о которых были удалены пользователем.';

