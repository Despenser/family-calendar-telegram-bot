package ru.golubyatnikov.family.calendar.bot.model;

/**
 * Категории сообщений для неавторизованных пользователей.
 *
 * @author Golubyatnikov Aleksey
 * @since 2026-01-16
 */
public enum MessageCategory {
    
    /**
     * Создание событий в календаре.
     * Используется для команды /add_event.
     */
    EVENT_CREATION,
    
    /**
     * Просмотр событий календаря.
     * Используется для команд /my_events, /month, /today, /week.
     */
    EVENT_VIEWING,
    
    /**
     * Управление событиями (редактирование, удаление).
     * Используется для команд редактирования и удаления событий.
     */
    EVENT_MANAGEMENT,
    
    /**
     * Поиск и фильтрация событий.
     * Используется для команд /search, /filter.
     */
    SEARCH_FILTER,
    
    /**
     * Управление корзиной удаленных событий.
     * Используется для команды /trash.
     */
    TRASH_MANAGEMENT,
    
    /**
     * Просмотр статистики.
     * Используется для команды /stats.
     */
    STATISTICS,
    
    /**
     * Общее сообщение для неопределенных категорий.
     * Используется как fallback для команд без специфичной категории.
     */
    GENERAL
}
