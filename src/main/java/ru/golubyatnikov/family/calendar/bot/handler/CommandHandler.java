package ru.golubyatnikov.family.calendar.bot.handler;

import org.telegram.telegrambots.meta.api.objects.Message;
import ru.golubyatnikov.family.calendar.bot.model.User;

/**
 * Интерфейс для обработчиков команд Telegram бота.
 * 
 * <p>Определяет контракт для всех обработчиков команд бота семейного календаря.
 * Каждая команда (например, /start, /add_event, /upcoming_events) должна иметь
 * свою реализацию этого интерфейса.</p>
 * 
 * <p>Обработчики команд отвечают за:</p>
 * <ul>
 *   <li>Обработку входящих сообщений от пользователей</li>
 *   <li>Выполнение бизнес-логики команды</li>
 *   <li>Формирование ответа пользователю</li>
 *   <li>Управление состоянием диалога (для многошаговых команд)</li>
 * </ul>
 * 
 * <p>Все реализации должны быть аннотированы {@code @Component} для автоматической
 * регистрации в Spring контексте и последующего использования в {@code CommandDispatcher}.</p>
 * 
 * <p><b>Архитектурный паттерн:</b> Command Pattern + Strategy Pattern</p>
 * <p><b>Требования:</b> 1.2</p>
 * 
 * <p><b>Пример использования:</b></p>
 * <pre>{@code
 * @Component
 * public class StartCommandHandler implements CommandHandler {
 *     
 *     @Override
 *     public String handle(Message message, User user) {
 *         return "Добро пожаловать в семейный календарь!";
 *     }
 *     
 *     @Override
 *     public String getCommand() {
 *         return "/start";
 *     }
 *     
 *     @Override
 *     public String getDescription() {
 *         return "Начать работу с ботом";
 *     }
 *     
 *     @Override
 *     public boolean requiresAuth() {
 *         return false; // /start доступен всем
 *     }
 * }
 * }</pre>
 * 
 * @see Message
 * @see User
 * @author Family Calendar Bot Team
 * @version 1.0.0
 * @since 2025-12-30
 */
public interface CommandHandler {

    /**
     * Обрабатывает команду от пользователя и возвращает текст ответа.
     * 
     * <p>Этот метод вызывается {@code CommandDispatcher} когда пользователь
     * отправляет команду, соответствующую этому обработчику.</p>
     * 
     * <p>Метод должен:</p>
     * <ul>
     *   <li>Извлечь необходимые данные из сообщения</li>
     *   <li>Выполнить бизнес-логику команды</li>
     *   <li>Сформировать понятный ответ пользователю</li>
     *   <li>Обработать возможные ошибки и вернуть соответствующее сообщение</li>
     * </ul>
     * 
     * <p><b>Важно:</b> Метод должен выполняться быстро (в пределах нескольких секунд),
     * так как Telegram ожидает ответ в течение 60 секунд. Для длительных операций
     * следует использовать асинхронную обработку.</p>
     * 
     * @param message входящее сообщение от Telegram, содержащее команду и параметры.
     *                Не может быть null. Содержит текст команды, информацию об отправителе,
     *                чате и другие метаданные.
     * @param user пользователь из базы данных, отправивший команду.
     *             Может быть null для команд, не требующих авторизации (например, /start).
     *             Содержит информацию о пользователе, его семье и настройках.
     * @return текст ответа, который будет отправлен пользователю.
     *         Может содержать Markdown форматирование для улучшения читаемости.
     *         Не должен быть null (вернуть пустую строку, если ответ не требуется).
     * @throws IllegalArgumentException если message равен null
     * @throws ru.golubyatnikov.family.calendar.bot.exception.UnauthorizedAccessException
     *         если команда требует авторизации, но user равен null
     * @throws ru.golubyatnikov.family.calendar.bot.exception.InvalidDateException
     *         если команда работает с датами и получены некорректные данные
     * @see Message
     * @see User
     */
    String handle(Message message, User user);

    /**
     * Возвращает команду, которую обрабатывает этот handler.
     * 
     * <p>Команда должна начинаться с символа "/" и быть в нижнем регистре.
     * Используется {@code CommandDispatcher} для маршрутизации входящих команд
     * к соответствующим обработчикам.</p>
     * 
     * <p><b>Примеры валидных команд:</b></p>
     * <ul>
     *   <li>/start - начало работы с ботом</li>
     *   <li>/help - справка по командам</li>
     *   <li>/add_event - добавление события</li>
     *   <li>/upcoming_events - просмотр предстоящих событий</li>
     *   <li>/my_events - просмотр своих событий</li>
     * </ul>
     * 
     * <p><b>Важно:</b> Каждый обработчик должен возвращать уникальную команду.
     * Если несколько обработчиков вернут одинаковую команду, поведение будет
     * непредсказуемым.</p>
     * 
     * @return строка с командой, начинающаяся с "/". Не может быть null или пустой.
     *         Должна быть в нижнем регистре для единообразия.
     * @see #getDescription()
     */
    String getCommand();

    /**
     * Возвращает описание команды для отображения в справке.
     * 
     * <p>Описание должно быть кратким (1-2 предложения) и понятным для пользователя.
     * Используется командой /help для формирования списка доступных команд.</p>
     * 
     * <p><b>Примеры хороших описаний:</b></p>
     * <ul>
     *   <li>"Начать работу с ботом" - для /start</li>
     *   <li>"Показать список всех команд" - для /help</li>
     *   <li>"Добавить новое событие в календарь" - для /add_event</li>
     *   <li>"Показать предстоящие события семьи" - для /upcoming_events</li>
     *   <li>"Управление моими событиями" - для /my_events</li>
     * </ul>
     * 
     * <p>Описание должно быть на русском языке и начинаться с заглавной буквы.</p>
     * 
     * @return строка с описанием команды. Не может быть null или пустой.
     *         Рекомендуемая длина: 20-60 символов.
     * @see #getCommand()
     */
    String getDescription();

    /**
     * Определяет, требуется ли авторизация для выполнения этой команды.
     * 
     * <p>Если метод возвращает {@code true}, {@code CommandDispatcher} проверит
     * наличие пользователя в базе данных перед вызовом {@link #handle(Message, User)}.
     * Если пользователь не найден, команда не будет выполнена, и пользователю
     * будет отправлено сообщение о необходимости регистрации.</p>
     * 
     * <p>Если метод возвращает {@code false}, команда будет выполнена для любого
     * пользователя, даже если он не зарегистрирован в системе.</p>
     * 
     * <p><b>Команды, не требующие авторизации:</b></p>
     * <ul>
     *   <li>/start - регистрация и приветствие</li>
     *   <li>/help - справка доступна всем</li>
     * </ul>
     * 
     * <p><b>Команды, требующие авторизации:</b></p>
     * <ul>
     *   <li>/add_event - только зарегистрированные пользователи могут создавать события</li>
     *   <li>/upcoming_events - требуется принадлежность к семье</li>
     *   <li>/my_events - требуется наличие аккаунта</li>
     * </ul>
     * 
     * <p><b>Реализация по умолчанию:</b> возвращает {@code true}, так как большинство
     * команд требуют авторизации. Переопределите этот метод, если команда должна
     * быть доступна неавторизованным пользователям.</p>
     * 
     * @return {@code true}, если команда требует авторизации (пользователь должен быть
     *         зарегистрирован в системе), {@code false} в противном случае.
     * @see User
     */
    default boolean requiresAuth() {
        return true;
    }
}
