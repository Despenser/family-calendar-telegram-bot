package ru.golubyatnikov.family.calendar.bot.model;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * Enum для типов фильтрации событий.
 * 
 * <p>Определяет доступные варианты фильтрации событий календаря по категориям.
 * Используется для персонализации отображения событий в зависимости от предпочтений пользователя.</p>
 * 
 * <p>Каждый тип фильтра имеет отображаемое имя (displayName), которое используется
 * в пользовательском интерфейсе для показа текущего активного фильтра.</p>
 * 
 * <p><b>Требования:</b> 2.1, 2.2, 2.3</p>
 * 
 * @author Family Calendar Bot Team
 * @version 1.0.0
 * @since 2026-01-16
 */
@Getter
@RequiredArgsConstructor
public enum EventFilter {
    
    /**
     * Показывать все события (семейные и личные).
     * Используется по умолчанию для новых пользователей.
     */
    ALL("Все события"),
    
    /**
     * Показывать только семейные события.
     * Фильтрует события, помеченные как семейные.
     */
    FAMILY("Семейные"),
    
    /**
     * Показывать только личные события.
     * Фильтрует события, помеченные как личные.
     */
    PERSONAL("Личные");
    
    /**
     * Отображаемое имя фильтра для пользовательского интерфейса.
     */
    private final String displayName;
}
